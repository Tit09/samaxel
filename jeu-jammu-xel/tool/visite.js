const {chromium}=require('playwright');
const W=+process.argv[2]||1280,H=+process.argv[3]||720,tag=process.argv[4]||'pc';
(async()=>{const b=await chromium.launch();const p=await b.newPage({viewport:{width:W,height:H},deviceScaleFactor:1});
p.on('pageerror',e=>console.log('ERR',e.message));p.on('console',m=>{if(m.type()==='error')console.log('CONSOLE',m.text())});
await p.goto('http://localhost:8090/');await p.waitForTimeout(6000);
await p.evaluate(()=>{const e=document.querySelector('flt-semantics-placeholder');if(e)e.click()});await p.waitForTimeout(800);
const shot=async n=>{await p.waitForTimeout(1200);await p.screenshot({path:`/home/claude/jeu/captures/${tag}_${n}.png`})};
const tap=async name=>{const el=p.getByRole('button',{name}).first();await el.click({timeout:5000})};
await shot('01_accueil');
await tap('Français');await shot('02_francais');
await tap(/Jouer/);await shot('03_coin');
await tap('Les émotions');await p.waitForTimeout(1500);await shot('04_emotions');
await p.goBack().catch(()=>{});
await p.getByRole('button',{name:'Retour'}).first().click().catch(()=>{});await p.waitForTimeout(800);
await tap('Ma journée');await shot('05_journee');await p.getByRole('button',{name:'Retour'}).first().click();await p.waitForTimeout(800);
await tap('Pareil');await shot('06_pareil');await p.getByRole('button',{name:'Retour'}).first().click();await p.waitForTimeout(800);
await tap('Je parle');await p.waitForTimeout(500);await tap("J'ai soif.");await shot('07_jeparle');await p.getByRole('button',{name:'Retour'}).first().click();await p.waitForTimeout(800);
await tap('Respirer');await p.waitForTimeout(2500);await shot('08_respirer');
await b.close()})();
